      prompt: '"Starry Night: A painting of swirling blue and yellow clouds over a sleeping village."',
      isAi: false,
      type: "Historical Artwork",
      explanation: "This classic masterpiece was painted by Vincent van Gogh in 1889, long before computers existed!"
