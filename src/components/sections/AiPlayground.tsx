                          className="px-6 py-3 md:px-8 md:py-4 rounded-xl border-2 border-[#0D47A1] text-[#0D47A1] font-black text-xs uppercase tracking-wider flex items-center gap-2 hover:bg-blue-50/20 transition-all cursor-pointer"
