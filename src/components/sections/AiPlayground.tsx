      options: ["Lidar sensors & cameras", "A magnifying glass", "A tiny remote control", "Magical flashlight eyes"],
      answerIdx: 0,
      explanation: "Self-driving cars use advanced Lidar (light detection and ranging) and camera sensors combined with AI to build a 3D model of their surroundings."
